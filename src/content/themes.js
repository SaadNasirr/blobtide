const DEFAULT = WORLDS[0];

export function worldForLevel(id) {
  const n = Math.max(1, id | 0);
  return WORLDS.find((w) => n >= w.from && n <= w.to) || DEFAULT;
}

export function attachWorld(level) {
  const world = worldForLevel(level.id);
  const wobble = ((level.id % 3) - 1) * 0.1;
  level.worldId = world.id;
  level.worldName = world.name;
  level.laneLimit = Math.max(2.55, Math.min(3.45, world.lane + wobble));
  return level;
}
