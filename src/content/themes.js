/** Shared visual worlds. One palette per band — geometries stay reused. */
export function fogRange(density) {
  const t = Math.max(0, (Number(density) - 0.5) / 1.5);
  return { near: Math.max(8, 46 - t * 32), far: Math.max(28, 118 - t * 66) };
}

export function levelFog(world, levelId) {
  const span = Math.max(1, (world.to || 1) - (world.from || 1));
  const u = Math.max(0, Math.min(1, ((levelId || world.from) - world.from) / span));
  const d = (world.fogDensity ?? 0.5) + u * 0.12;
  return fogRange(d);
}

/** Sunrise (0) → overhead (0.5) → sunset behind the track (1). */
export function sunPosition(sunT = 0.35) {
  const t = Math.max(0, Math.min(1, sunT));
  return {
    x: Math.cos(t * Math.PI) * 16,
    y: 5 + Math.sin(t * Math.PI) * 13,
    z: -2 + t * 18,
  };
}

